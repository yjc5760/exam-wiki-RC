# 需要「取代既有區塊」而非單純插入的圖（例如 ASCII art 圖說）
# 需要「取代既有區塊」而非單純插入的圖（目前無）
REPLACE = {}


FIG_DATE = {mid: "2026-09-02" for mid in
            ("RC-2020-2", "RC-2014-3", "RC-2009-3", "RC-2017-2", "RC-2023-3")}
FIG_DATE.update({mid: "2026-09-07" for mid in
                 ("RC-2025-2", "RC-2013-2", "RC-2012-3", "RC-2005-3", "RC-2022-4")})


def apply_one(mid, entries):
    md = os.path.join(ROOT, "raw", "solutions", mid, mid + ".md")
    figdir = os.path.join(ROOT, "raw", "solutions", mid, "figs")
    if not os.path.exists(md):
        print(f"  跳過 {mid}：找不到 {md}")
        return False
    missing = [e[0] for e in entries
               if not os.path.exists(os.path.join(figdir, f"{mid}-fig-{e[0]}.svg"))]
    if missing:
        print(f"  跳過 {mid}：figs/ 缺少 {missing}")
        return False

    raw = open(md, "rb").read()
    crlf = raw.count(b"\r\n") > 0 and raw.count(b"\r\n") == raw.count(b"\n")
    s = raw.decode("utf-8").replace("\r\n", "\n")

    if f"figs/{mid}-fig-{entries[0][0]}.svg" in s:
        print(f"  跳過 {mid}：圖片連結已存在（冪等）")
        return False

    def block(e):
        suffix, num, alt, cap = e
        return (f"![{alt}](figs/{mid}-fig-{suffix}.svg)\n\n"
                f"*圖 {num}　{cap}*\n\n")

    anch = ANCHORS.get(mid, {})
    placed, fallback = set(), []
    for e in entries:
        suffix = e[0]
        key = (mid, suffix)
        if key in REPLACE:                              # 取代既有區塊（如 ASCII art）
            pre, post, keep = REPLACE[key]
            a = s.find(pre)
            assert a >= 0, f"{mid} {suffix}：找不到待取代區塊起點"
            b = s.index(post, a + len(pre)) + len(post)
            s = s[:a] + keep + block(e) + s[b:]
            placed.add(suffix); continue
        a = anch.get(suffix)
        if a is None:
            fallback.append(e); continue
        assert s.count(a) == 1, f"{mid} {suffix}：錨點出現 {s.count(a)} 次"
        j = s.index(a) + len(a)
        s = s[:j] + "\n\n" + block(e).rstrip("\n") + s[j:]
        placed.add(suffix)

    if fallback:                                        # 沒給錨點的沿用舊規則
        m5 = re.search(r"^## 5\.", s, flags=re.M)
        m2 = re.search(r"^## 2\.", s, flags=re.M)
        if not m2 or not m5:
            print(f"  跳過 {mid}：找不到 §2 或 §5 標題")
            return False
        rest = "".join(block(e) for e in fallback if e is not entries[0])
        s = s[:m5.start()] + rest + s[m5.start():]
        if entries[0] in fallback:
            m2 = re.search(r"^## 2\.", s, flags=re.M)
            s = s[:m2.start()] + block(entries[0]) + s[m2.start():]

    # 檔尾補記
    tail = (f"\n*圖解補繪：{FIG_DATE.get(mid, '2026-08-21')}（向量圖 {len(entries)} 張，"
            f"腳本 `figs/gen_{mid}.py`，可重跑；腳本檔尾對 §4 公佈值做 assert）*\n")
    s = s.rstrip("\n") + "\n" + tail

    if DRY:
        print(f"  [dry] {mid}：會插入 {len(entries)} 張圖")
        return True
    open(md, "wb").write((s.replace("\n", "\r\n") if crlf else s).encode("utf-8"))
    print(f"  已插入 {mid}：{len(entries)} 張圖")
    return True


def main():
    print("── 插入圖解 ──")
    done = [mid for mid, e in FIGS.items() if apply_one(mid, e)]
    if DRY or not done:
        return
    gen = os.path.join(ROOT, "scripts", "gen_problems_view.py")
    if os.path.exists(gen):
        print("\n── 重建 problems-view ──")
        subprocess.run([sys.executable, gen, ROOT] + done, check=False)
    else:
        print(f"\n找不到 {gen}，請自行重建 problems-view")


if __name__ == "__main__":
    main()
